	<h3 id="6-how-winners-are-picked">6. How Winners Are Picked</h3>
	<p>Winners are picked by the Syntax team (the "Judges"). We never pick winners at random.</p>
	<ul>
		<li>
			<strong>Comment Pick:</strong> We pick comments we like, for whatever reason they stand out. It
			might be a useful tip or correction, kindness toward another community member, something that made
			us laugh, or just a great comment. There's no scoring formula. Picks are up to the Judges, can happen
			on any video or livestream, and may happen often, rarely, or never. Most comments and most videos
			won't have a winner.
		</li>
		<li><strong>Trivia:</strong> The first correct answer wins, unless the host says otherwise.</li>
		<li>
			<strong>First Correct Answer:</strong> The first correct answer wins, based on YouTube's timestamp.
			The Judges decide what counts as correct.
		</li>
	</ul>
	<p>
		The host may say how many winners there will be. If not, there's one (or, for Comment Pick, as
		many or as few as we like). The Judges' decisions are final.
	</p>
